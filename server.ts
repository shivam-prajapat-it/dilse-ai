import express from 'express';
import { createServer as createViteServer } from 'vite';
import path from 'path';
import dotenv from 'dotenv';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

type SupportedLanguage = 'hi' | 'hinglish' | 'en';

interface ChatHistoryItem {
  role: 'user' | 'assistant';
  content: string;
}

function getGenAIClient(): GoogleGenAI {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey || apiKey === 'MY_GEMINI_API_KEY') {
    throw new Error('GEMINI_API_KEY is not configured.');
  }
  return new GoogleGenAI({
    apiKey,
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      },
    },
  });
}

const BASE_SYSTEM_INSTRUCTION = `You are DilSe AI, a warm, thoughtful, emotionally intelligent, human-like conversational assistant specializing in love and relationships.

Speak naturally, as if you are a caring and mature friend who genuinely listens. Be empathetic, patient, respectful, and non-judgmental.

Answer questions about the importance of love, relationships, trust, loyalty, emotional connection, misunderstandings, heartbreak, communication, self-respect, and healthy boundaries.

Always understand the user's question before answering. Respond directly and naturally. Avoid robotic language, repetitive introductions, unnecessary disclaimers, and long answers when a short answer is enough.

If the user shares a personal problem, acknowledge their feelings and give balanced, practical advice. Never assume you know what another person is thinking or feeling.

Support Hindi, Hinglish, and English. When the user speaks or writes in Hindi or Hinglish, answer in simple, natural Hindi using Devanagari script by default, unless the user requests another language.

For voice replies, generate natural, conversational spoken responses. Keep most voice answers concise and easy to understand.

Be honest that you are an AI assistant. Never claim to be a real human. Encourage healthy real-world relationships, personal autonomy, mutual consent, and respect. Do not encourage manipulation, stalking, or controlling behavior.`;

function buildSystemInstruction(selectedLanguage: SupportedLanguage): string {
  if (selectedLanguage === 'hinglish') {
    return `${BASE_SYSTEM_INSTRUCTION}\n\nCurrent Language Preference: The user has selected Hinglish in the language selector. Unless the user writes in Devanagari Hindi or explicitly asks for Hindi or English, respond in warm, simple, natural Hinglish (Hindi in Roman script).`;
  }
  if (selectedLanguage === 'en') {
    return `${BASE_SYSTEM_INSTRUCTION}\n\nCurrent Language Preference: The user has selected English in the language selector. If the user writes in English, respond in warm, natural English. However, if the user speaks or writes in Hindi or Hinglish (such as "Pyaar zindagi mein kyun zaroori hai?"), answer in simple, natural Hindi using Devanagari script unless they explicitly ask for English.`;
  }
  return `${BASE_SYSTEM_INSTRUCTION}\n\nCurrent Language Preference: हिंदी (Devanagari). Unless the user explicitly requests English or Hinglish in their message, always respond in simple, warm, conversational Hindi using Devanagari script (देवनागरी लिपि). Avoid overly difficult Sanskritized words or literal word-for-word English translations.`;
}

async function startServer() {
  const app = express();
  const PORT = 3000;

  app.use(express.json({ limit: '10mb' }));

  // Chat endpoint powered by Gemini
  app.post('/api/chat', async (req, res) => {
    try {
      const { message, selectedLanguage = 'hi', history = [] } = req.body as {
        message?: string;
        selectedLanguage?: SupportedLanguage;
        history?: ChatHistoryItem[];
      };

      if (!message || !message.trim()) {
        res.status(400).json({ error: 'Empty message' });
        return;
      }

      const ai = getGenAIClient();

      const contents = [
        ...history.slice(-12).map((item) => ({
          role: item.role === 'user' ? 'user' : 'model',
          parts: [{ text: item.content }],
        })),
        {
          role: 'user',
          parts: [{ text: message.trim() }],
        },
      ];

      const response = await ai.models.generateContent({
        model: 'gemini-3.8-flash',
        contents,
        config: {
          systemInstruction: buildSystemInstruction(selectedLanguage),
          temperature: 0.7,
        },
      });

      const replyText = response.text?.trim();
      if (!replyText) {
        res.status(502).json({ error: 'No response generated by Gemini.' });
        return;
      }

      res.json({
        reply: replyText,
      });
    } catch (error) {
      console.error('Error in /api/chat:', error);
      res.status(500).json({
        error: error instanceof Error ? error.message : 'Failed to generate response',
      });
    }
  });

  // Natural AI Voice Reply (TTS) endpoint using Gemini TTS
  app.post('/api/tts', async (req, res) => {
    try {
      const { text } = req.body as { text?: string };
      if (!text || !text.trim()) {
        res.status(400).json({ error: 'Text is required for speech synthesis' });
        return;
      }

      const ai = getGenAIClient();
      const response = await ai.models.generateContent({
        model: 'gemini-3.8-flash-lite-tts',
        contents: [
          {
            role: 'user',
            parts: [
              {
                text: text.trim(),
              },
            ],
          },
        ],
        config: {
          responseModalities: ['AUDIO'],
          speechConfig: {
            voiceConfig: {
              prebuiltVoiceConfig: { voiceName: 'Kore' },
            },
          },
        },
      });

      const base64Audio =
        response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;

      if (!base64Audio) {
        res.status(502).json({ error: 'No audio returned from TTS model' });
        return;
      }

      res.json({
        audioBase64: base64Audio,
        mimeType: 'audio/wav',
      });
    } catch (error) {
      console.error('Error in /api/tts:', error);
      res.status(500).json({
        error: error instanceof Error ? error.message : 'TTS generation failed',
      });
    }
  });

  // Speech-to-Text endpoint using Gemini Transcribe (fallback if browser SpeechRecognition is unavailable)
  app.post('/api/transcribe', async (req, res) => {
    try {
      const { audioBase64, mimeType = 'audio/webm' } = req.body as {
        audioBase64?: string;
        mimeType?: string;
      };

      if (!audioBase64) {
        res.status(400).json({ error: 'Audio data is required' });
        return;
      }

      const ai = getGenAIClient();
      const response = await ai.models.generateContent({
        model: 'gemini-3.5-transcribe',
        contents: {
          parts: [
            {
              inlineData: {
                mimeType,
                data: audioBase64,
              },
            },
            {
              text: 'Transcribe the spoken words accurately in the language spoken (Hindi Devanagari, Hinglish, or English). If there is only silence or background noise and no clear human speech, return an empty string "". Do not invent or guess words.',
            },
          ],
        },
      });

      const transcript = (response.text || '').trim();
      res.json({ transcript });
    } catch (error) {
      console.error('Error in /api/transcribe:', error);
      res.status(500).json({
        error: error instanceof Error ? error.message : 'Transcription failed',
      });
    }
  });

  if (process.env.NODE_ENV !== 'production') {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), 'dist');
    app.use(express.static(distPath));
    app.get('*', (_req, res) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`DilSe AI server listening on http://localhost:${PORT}`);
  });
}

startServer();
